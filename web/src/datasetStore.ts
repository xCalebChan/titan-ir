const STORAGE_KEY_CUSTOM_DATASET = 'titan_custom_dataset_v1';
const STORAGE_KEY_ACTIVE_ID = 'titan_active_dataset_id_v1';

// Listeners for reactive updates
const listeners = new Set<() => void>();
export function subscribeDatasetChange(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

function notifyListeners() {
  listeners.forEach((fn) => fn());
}

export function getCustomDataset(): { meta: DatasetMeta; passages: DocumentPassage[] } | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_CUSTOM_DATASET);
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    if (parsed && Array.isArray(parsed.passages) && parsed.passages.length > 0) {
      return {
        meta: {
          id: 'custom',
          name: parsed.name || 'Imported Custom Dataset',
          description: parsed.description || `User-imported corpus of ${parsed.passages.length} documents.`,
          document_count: parsed.passages.length,
          is_custom: true,
          indexed_at: parsed.indexed_at || new Date().toISOString(),
        },
        passages: parsed.passages,
      };
    }
  } catch (e) {
    console.warn('Failed to load custom dataset from localStorage', e);
  }
  return null;
}

export function saveCustomDataset(name: string, passages: DocumentPassage[]): DatasetMeta {
  const meta: DatasetMeta = {
    id: 'custom',
    name: name.trim() || 'Imported Custom Dataset',
    description: `User-imported corpus of ${passages.length} documents indexed into search engine.`,
    document_count: passages.length,
    is_custom: true,
    indexed_at: new Date().toISOString(),
  };

  try {
    localStorage.setItem(
      STORAGE_KEY_CUSTOM_DATASET,
      JSON.stringify({
        name: meta.name,
        description: meta.description,
        indexed_at: meta.indexed_at,
        passages,
      })
    );
  } catch (e) {
    console.error('Failed to save custom dataset to localStorage', e);
  }

  setActiveDatasetId('custom');
  return meta;
}

export function getActiveDatasetId(): string {
  try {
    return localStorage.getItem(STORAGE_KEY_ACTIVE_ID) || 'msmarco';
  } catch {
    return 'msmarco';
  }
}

export function setActiveDatasetId(id: string): void {
  try {
    localStorage.setItem(STORAGE_KEY_ACTIVE_ID, id);
  } catch (e) {
    console.warn('Failed to save active dataset id to localStorage', e);
  }
  notifyListeners();
}

export function getActiveDataset(): { meta: DatasetMeta; passages: DocumentPassage[] } {
  const activeId = getActiveDatasetId();

  if (activeId === 'custom') {
    const custom = getCustomDataset();
    if (custom && custom.passages.length > 0) {
      return custom;
    }
  }

  if (activeId === 'ai-ml') {
    return { meta: AIML_DATASET_META, passages: AIML_PASSAGES };
  }

  if (activeId === 'systems') {
    return { meta: SYSTEMS_DATASET_META, passages: SYSTEMS_PASSAGES };
  }

  return { meta: MSMARCO_DATASET_META, passages: SAMPLE_PASSAGES };
}

export function resetToDefaultDataset(): void {
  setActiveDatasetId('msmarco');
}

/**
 * Universal parser supporting:
 * 1. JSON Array of objects: [{"title": "...", "body": "...", "url": "..."}]
 * 2. CSV / TSV with headers or rows
 * 3. One document per line / paragraph (Title: Body or Raw text)
 */
export function parseDatasetText(
  rawText: string,
  format: 'auto' | 'json' | 'csv' | 'lines'
): { success: boolean; passages: DocumentPassage[]; error?: string } {
  const trimmed = rawText.trim();
  if (!trimmed) {
    return { success: false, passages: [], error: 'Dataset content is empty.' };
  }

  // 1. Try JSON if requested or auto-detected
  if (format === 'json' || (format === 'auto' && (trimmed.startsWith('[') || trimmed.startsWith('{')))) {
    try {
      const parsed = JSON.parse(trimmed);
      const items = Array.isArray(parsed) ? parsed : [parsed];
      const passages: DocumentPassage[] = items
        .filter((item) => item && (item.body || item.text || item.content || item.title))
        .map((item, idx) => ({
          doc_id: idx,
          title: item.title || item.name || `Document #${idx + 1}`,
          body: item.body || item.text || item.content || item.passage || String(item),
          url: item.url || item.link || undefined,
        }));

      if (passages.length > 0) {
        return { success: true, passages };
      }
    } catch (e: any) {
      if (format === 'json') {
        return { success: false, passages: [], error: `Invalid JSON syntax: ${e.message}` };
      }
    }
  }

  // 2. Try CSV / TSV if requested or contains comma/tab separated lines
  if (format === 'csv' || (format === 'auto' && (trimmed.includes(',') || trimmed.includes('\t')))) {
    const lines = trimmed.split(/\r?\n/).filter((l) => l.trim().length > 0);
    if (lines.length > 1) {
      const isTsv = lines[0].includes('\t');
      const delimiter = isTsv ? '\t' : ',';
      const firstLineCols = lines[0].split(delimiter).map((c) => c.trim().toLowerCase());
      const hasHeaders =
        firstLineCols.some((c) => c.includes('title') || c.includes('text') || c.includes('body'));

      const dataLines = hasHeaders ? lines.slice(1) : lines;
      const titleCol = hasHeaders ? firstLineCols.findIndex((c) => c.includes('title')) : 0;
      const bodyCol = hasHeaders ? firstLineCols.findIndex((c) => c.includes('body') || c.includes('text')) : 1;
      const urlCol = hasHeaders ? firstLineCols.findIndex((c) => c.includes('url') || c.includes('link')) : 2;

      const passages: DocumentPassage[] = dataLines.map((line, idx) => {
        const parts = line.split(delimiter);
        const title = (parts[titleCol >= 0 ? titleCol : 0] || `Row #${idx + 1}`).trim().replace(/^["']|["']$/g, '');
        const body = (parts[bodyCol >= 0 ? bodyCol : 1] || parts[0] || '').trim().replace(/^["']|["']$/g, '');
        const url = urlCol >= 0 && parts[urlCol] ? parts[urlCol].trim().replace(/^["']|["']$/g, '') : undefined;
        return {
          doc_id: idx,
          title: title || `Document #${idx + 1}`,
          body: body || title,
          url,
        };
      });

      if (passages.length > 0) {
        return { success: true, passages };
      }
    }
  }

  // 3. Plain text / Paragraphs (Double newline or single line per doc)
  const paragraphs = trimmed
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0);

  const entries = paragraphs.length > 1 ? paragraphs : trimmed.split(/\r?\n/).filter((l) => l.trim().length > 0);

  const passages: DocumentPassage[] = entries.map((entry, idx) => {
    // If has "Title: Body" format
    const colonMatch = entry.match(/^([^:\n]{3,60}):\s+(.+)$/s);
    if (colonMatch) {
      return {
        doc_id: idx,
        title: colonMatch[1].trim(),
        body: colonMatch[2].trim(),
      };
    }

    const firstPeriod = entry.indexOf('.');
    const title =
      firstPeriod > 5 && firstPeriod < 70
        ? entry.slice(0, firstPeriod).trim()
        : entry.slice(0, 50).trim() + '...';

    return {
      doc_id: idx,
      title: title || `Passage #${idx + 1}`,
      body: entry,
    };
  });

  return { success: true, passages };
}
